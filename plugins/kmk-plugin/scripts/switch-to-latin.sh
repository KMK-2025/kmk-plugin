#!/usr/bin/env bash
# ==========================================================
#  تبديل أسماء الأوامر من العربية إلى اللاتينية
#  شغّله فقط إذا كانت طرفية المتدرب لا تتعامل جيدًا مع العربية.
#  الاستخدام:  bash تبديل-للاتينية.sh /مسار/المشروع
#  للرجوع:     bash تبديل-للاتينية.sh /مسار/المشروع --رجوع
# ==========================================================
set -e

TARGET="${1:-.}"
MODE="${2:-}"
S="$TARGET/.claude/skills"

[ -d "$S" ] || { echo "❌ لم أجد $S"; exit 1; }

declare -A MAP=(
  [فكرة]=idea
  [صمم]=design
  [ابن]=build
  [جرب]=test
  [انشر]=deploy
  [اصلح]=fix
  [شارك]=share
  [تراجع]=undo
)

if [ "$MODE" = "--رجوع" ]; then
  for ar in "${!MAP[@]}"; do
    en="${MAP[$ar]}"
    [ -d "$S/$en" ] && mv "$S/$en" "$S/$ar" && echo "  ← /$ar"
  done
  echo "✅ رجعت الأوامر للعربية."
else
  for ar in "${!MAP[@]}"; do
    en="${MAP[$ar]}"
    [ -d "$S/$ar" ] && mv "$S/$ar" "$S/$en" && echo "  → /$en"
  done
  echo "✅ صارت الأوامر لاتينية."
  echo "   لا تنسَ: البطاقة فيها نسخة بديلة جاهزة بهذه الأسماء."
fi

echo
echo "الأوامر الحالية:"
ls -1 "$S" | sed 's|^|  /|'
